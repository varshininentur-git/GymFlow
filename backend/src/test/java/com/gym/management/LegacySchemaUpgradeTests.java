package com.gym.management;

import com.gym.management.entity.*;
import com.gym.management.repository.*;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import java.sql.DriverManager;
import java.time.LocalDate;
import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
@AutoConfigureTestDatabase(replace=AutoConfigureTestDatabase.Replace.NONE)
class LegacySchemaUpgradeTests {
    private static final String URL="jdbc:h2:mem:legacyupgradetest;DB_CLOSE_DELAY=-1;DB_CLOSE_ON_EXIT=FALSE";

    static {
        try(var connection=DriverManager.getConnection(URL,"sa","");var statement=connection.createStatement()) {
            statement.execute("create table gym_users (id bigint generated by default as identity primary key, created_at timestamp(6) with time zone not null, enabled boolean not null, password_hash varchar(100) not null, role enum ('ADMIN','STAFF') not null, username varchar(80) not null unique)");
            statement.execute("insert into gym_users(created_at,enabled,password_hash,role,username) values(current_timestamp,true,'not-a-login-hash','ADMIN','legacy-admin')");
        } catch(Exception e) { throw new ExceptionInInitializerError(e); }
    }

    @DynamicPropertySource static void properties(DynamicPropertyRegistry registry) {
        registry.add("spring.datasource.url",()->URL);
        registry.add("spring.datasource.username",()->"sa");
        registry.add("spring.datasource.password",()->"");
        registry.add("spring.jpa.hibernate.ddl-auto",()->"update");
    }

    @Autowired GymUserRepository users;
    @Autowired MemberRepository members;

    @Test void updatePreservesOldAccountsAndAllowsLinkedMemberAccounts() {
        GymUser old=users.findByUsernameIgnoreCase("legacy-admin").orElseThrow();
        assertEquals(Role.ADMIN,old.getRole());
        Member member=new Member();member.setFullName("Schema test member");member.setEmail("schema-upgrade@example.test");member.setPhone("5550100");member.setCategory(MemberCategory.GIRLS);member.setJoiningDate(LocalDate.now());
        member=members.saveAndFlush(member);
        GymUser account=users.saveAndFlush(new GymUser("schema-member","test-password-hash",member));
        assertEquals(Role.MEMBER,users.findById(account.getId()).orElseThrow().getRole());
        assertEquals(member.getId(),users.findByUsernameIgnoreCase("schema-member").orElseThrow().getMember().getId());
        assertEquals(Role.ADMIN,users.findByUsernameIgnoreCase("legacy-admin").orElseThrow().getRole());
    }
}
